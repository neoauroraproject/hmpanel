function deepMerge(a, b) {
  const out = { ...a };
  for (const [k, v] of Object.entries(b)) {
    out[k] = v && typeof v === "object" && !Array.isArray(v) && typeof a[k] === "object"
      ? deepMerge(a[k], v)
      : v;
  }
  return out;
}

function count(obj) {
  let n = 0;
  for (const v of Object.values(obj)) n += typeof v === "string" ? 1 : count(v);
  return n;
}

